#!/usr/bin/env python3
"""Generate src/tokenizer/unicode_tables.rs: the character classes the pre-tokeniser regexes use.

Classes (bit flags): N = \\p{N}, L = \\p{L}, WS = \\s (Unicode White_Space, which is what Oniguruma's \\s
matches). GLM-5.3's one split pattern uses only these three (see tokenizer/pretok.rs); everything else is
"other" (`[^\\s\\p{L}\\p{N}]`).

Categories come from UnicodeData.txt of Unicode 16.0, which is what the reference's Oniguruma
(tokenizers 0.22) uses: with an older Unicode the code-point sweep in gen_tokenizer_cases.py
disagrees on characters added in 16.0 (found on the DeepSeek front-end). Get it with
    curl -o UnicodeData.txt https://www.unicode.org/Public/16.0.0/ucd/UnicodeData.txt
and run: gen_unicode_tables.py UnicodeData.txt src/tokenizer/unicode_tables.rs
"""
import sys

N, L, WS = 1, 2, 8
WHITE_SPACE = set(range(0x09, 0x0E)) | {0x20, 0x85, 0xA0, 0x1680} | set(range(0x2000, 0x200B)) | {
    0x2028, 0x2029, 0x202F, 0x205F, 0x3000}


CATEGORY = {}


def load_ucd(path: str) -> None:
    first = None
    for line in open(path):
        f = line.split(";")
        cp, name, cat = int(f[0], 16), f[1], f[2]
        if name.endswith(", First>"):
            first = cp
            continue
        if name.endswith(", Last>"):
            for c in range(first, cp + 1):
                CATEGORY[c] = cat
            continue
        CATEGORY[cp] = cat


def flags(cp: int) -> int:
    cat = CATEGORY.get(cp, "Cn")
    f = 0
    if cat[0] == "N":
        f |= N
    if cat[0] == "L":
        f |= L
    if cp in WHITE_SPACE:
        f |= WS
    return f


def main(ucd_path: str, out_path: str) -> None:
    load_ucd(ucd_path)
    ranges = []
    start, cur = 0, flags(0)
    for cp in range(1, 0x110000):
        f = flags(cp) if not (0xD800 <= cp <= 0xDFFF) else 0
        if f != cur:
            if cur:
                ranges.append((start, cp - 1, cur))
            start, cur = cp, f
    if cur:
        ranges.append((start, 0x10FFFF, cur))
    with open(out_path, "w") as fh:
        fh.write("// Generated by tools/gen_unicode_tables.py from UnicodeData.txt 16.0.0 (Unicode Character Database, Copyright Unicode, Inc., Unicode License v3; the root NOTICE). Do not edit.\n")
        fh.write("// (first, last, flags) for every run of code points with the same non-zero flags.\n")
        fh.write("pub const CLASS_RANGES: &[(u32, u32, u8)] = &[\n")
        for a, b, f in ranges:
            fh.write(f"    (0x{a:X}, 0x{b:X}, {f}),\n")
        fh.write("];\n")
    print(f"{len(ranges)} ranges -> {out_path}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
